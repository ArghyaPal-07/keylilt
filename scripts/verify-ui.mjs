import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { calculateMetrics } from '../src/utils/typingMetrics.js';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.KEYLILT_PLAYWRIGHT_MODULE || 'playwright');
assert.deepEqual(calculateMetrics(150, 0, 30), {wpm:60,accuracy:"100.00"});
assert.deepEqual(calculateMetrics(150, 15, 30), {wpm:54,accuracy:"90.00"});
assert.deepEqual(calculateMetrics(0, 0, 0), {wpm:0,accuracy:"0.00"});
assert.deepEqual(calculateMetrics(2, 4, 30), {wpm:0,accuracy:"0.00"});
const browser = await chromium.launch({channel:'msedge',headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror', e=>errors.push(e.message));
page.on('console', m=>{if(m.type()==='error') errors.push(m.text());});
await page.goto('http://127.0.0.1:4175/');
await page.locator('#typing-input').waitFor();
await page.screenshot({path:'artifacts/practice-desktop.png'});
const words=await page.locator('.typing-words').innerText();
await page.locator('#typing-input').pressSequentially(words.slice(0,5),{delay:80});
assert.equal(await page.locator('.live-metrics dd').nth(2).innerText(),'0');
await page.locator('#typing-input').pressSequentially('~');
assert.equal(await page.locator('.live-metrics dd').nth(2).innerText(),'1');
await page.keyboard.press('Backspace');
await page.keyboard.press('Escape');
assert.equal(await page.locator('#typing-input').inputValue(),'');
assert.equal(await page.locator('.timer').innerText(),'30s');
assert.equal(await page.locator('.live-metrics dd').nth(0).innerText(),'0');
assert.equal(await page.locator('.live-metrics dd').nth(2).innerText(),'0');
assert.equal(await page.locator('.typing-words .active-char').count(),1);
const nextWords=await page.locator('.typing-words').innerText();
await page.locator('#typing-input').pressSequentially(nextWords,{delay:10});
await page.waitForURL('**/results');
assert.equal(await page.locator('.result-metrics dd').nth(0).innerText(),'100.00%');
assert.equal(await page.locator('.result-metrics dd').nth(1).innerText(),'0');
assert.ok(parseFloat(await page.locator('.result-metrics dd').nth(2).innerText())>0);
assert.equal((await page.locator('.primary-button').innerText()).replace(/\s/g,''),'TryAgain↗');
await page.screenshot({path:'artifacts/results-desktop.png'});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'artifacts/results-mobile.png'});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true);
await page.keyboard.press('Enter');
await page.waitForURL('**/typing');
assert.equal(await page.locator('#typing-input').inputValue(),'');
assert.equal(await page.locator('.timer').innerText(),'30s');
assert.equal(await page.locator('.live-metrics dd').nth(2).innerText(),'0');
assert.ok(await page.locator('#typing-input').evaluate(el=>el===document.activeElement));
await page.screenshot({path:'artifacts/practice-mobile.png'});
await page.locator('#typing-input').pressSequentially('~');
try { await page.waitForURL('**/results',{timeout:35000}); } catch (error) { console.log(await page.locator('body').innerText()); throw error; }
assert.equal(await page.locator('.result-metrics dd').nth(2).innerText(),'30s');
assert.equal(await page.locator('.result-metrics dd').nth(1).innerText(),'1');
assert.equal(await page.locator('.result-metrics dd').nth(0).innerText(),'0.00%');
await page.getByRole('button',{name:'Try Again'}).click();
await page.waitForURL('**/typing');
await page.goto('http://127.0.0.1:4175/results');
assert.equal(await page.getByText('Test completed',{exact:true}).count(),0);
assert.ok(await page.getByText('Complete a typing test to see your results here.').isVisible());
for(const asset of ['/brand/icon.svg','/brand/favicon.svg','/brand/app-icon.png','/manifest.webmanifest']) {
 assert.equal((await page.request.get('http://127.0.0.1:4175'+asset)).status(),200);
}
await page.goto('http://127.0.0.1:4175/leaderboard');
assert.ok(await page.getByText('Leaderboard is unavailable',{exact:false}).isVisible());
assert.deepEqual(errors,[]);
await browser.close();
console.log('PASS: metric formula, correct/error input, backspace, Escape reset, early completion, real 30-second timeout, Enter/button retry, empty results, mobile overflow, assets, guest leaderboard, console.');
